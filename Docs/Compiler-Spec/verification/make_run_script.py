#!/usr/bin/env python3
"""Generate an AmigaDOS script that compiles and runs the probe programs.

The script is meant to be executed by the Workbench startup of the test
emulator (Amiberry). It expects:

  AB3:      the AmiBlitz3 distribution (copy of this repository)
  SPEC:     this verification directory (probes/ and results/)

Usage:  make_run_script.py [probe ...]   (default: all probes/*.ab3 that are
        not include files) > run.script
"""
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
PROBES = HERE / "probes"
# include-only files are compiled through their main file
INCLUDE_ONLY = {"include_sub", "join_inc_sub"}
# probes that may crash the compiler run last
LAST = ["esc_empty"]


def main(argv):
    if argv:
        names = argv
    else:
        names = sorted(p.stem for p in PROBES.glob("*.ab3")
                       if p.stem not in INCLUDE_ONLY)
        names = [n for n in names if n not in LAST] + \
                [n for n in LAST if (PROBES / f"{n}.ab3").exists()]

    out = [
        "; generated by make_run_script.py - do not edit",
        "FailAt 21",
        "Stack 200000",
        "Delete SPEC:results/#?.(txt|log) SPEC:results/done QUIET",
        "CD AB3:",
        "AmiBlitz3 -dump token SPEC:results/tokens.txt"
        " >SPEC:results/tokens.log",
    ]
    for n in names:
        src = f"SPEC:probes/{n}.ab3"
        exe = f"RAM:{n}"
        res = f"SPEC:results/{n}"
        out += [
            f"Echo \"{n}\" >>SPEC:results/progress.txt",
            f"AmiBlitz3 -s {src} -e {exe} >{res}.compile.txt",
            f"IF EXISTS {exe}",
            f"  {exe} >{res}.run.txt",
            f"  Delete {exe} QUIET",
            "ENDIF",
        ]
    out.append("Echo \"done\" >SPEC:results/done")
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main(sys.argv[1:])
